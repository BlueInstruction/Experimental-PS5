#!/usr/bin/env python3
"""Generate ShaderCacheVersion.hpp for the PX5-vendored shader recompiler.

Mirrors AnyPS5's ShaderCacheVersion.cmake semantics in simplified form:
  - SourceVersion: order-independent digest over every vendored source file
    (relative path + SHA-256), so any edit to the vendored tree invalidates
    the shader disk cache.
  - RecompilerSwitches: every "APS5_*" environment-switch string literal that
    appears in the vendored sources (the recompiler's debug toggles).

The header is committed (generated/ShaderCacheVersion.hpp); re-run this script
whenever the vendored tree is updated from upstream AnyPS5.
"""
import hashlib
import re
import sys
from pathlib import Path

# Repo root = parent of tools/ (this script lives in tools/).
REPO_ROOT = Path(__file__).resolve().parent.parent
ROOT = REPO_ROOT / "app/src/main/cpp/gpu/shader_recompiler"
OUT = ROOT / "generated" / "ShaderCacheVersion.hpp"

SWITCH_RE = re.compile(r'"(APS5_[A-Z0-9_]+)"')


def main() -> int:
    sources = sorted(p for p in ROOT.rglob("*")
                     if p.suffix in (".cpp", ".hpp", ".h") and "generated" not in p.parts)
    if not sources:
        print("no sources found", file=sys.stderr)
        return 1

    combined = hashlib.sha256()
    for path in sources:
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        relative = path.relative_to(ROOT).as_posix()
        combined.update(f"{relative}:{digest}\n".encode())

    switches: set[str] = set()
    for path in sources:
        for match in SWITCH_RE.finditer(path.read_text(errors="replace")):
            switches.add(match.group(1))

    switch_list = "\n".join(f'    "{name}",' for name in sorted(switches))
    header = f"""// Generated by scripts/gen_shader_cache_version.py — do not edit by hand.
// SourceVersion changes whenever any vendored recompiler source changes,
// invalidating every on-disk compiled-shader entry (AnyPS5 semantics).
#ifndef PX5_SHADER_RECOMPILER_GENERATED_SHADER_CACHE_VERSION_HPP
#define PX5_SHADER_RECOMPILER_GENERATED_SHADER_CACHE_VERSION_HPP

#include <cstdint>
#include <string_view>

namespace ShaderRecompiler::ShaderDiskCache::Generated {{

inline constexpr std::uint64_t SourceVersion = 0x{combined.hexdigest()[:16]}ull;

inline constexpr std::string_view RecompilerSwitches[] = {{
{switch_list}
}};

}}

#endif
"""
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(header)
    print(f"wrote {OUT} ({len(sources)} files hashed, {len(switches)} switches)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
